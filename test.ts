// v0.4 の全ブロックを1回ずつ呼ぶ（ビルドが通るかを見るため。遊べるゲームではない）
W26Event.onStart(function () {
    W26Game.setLimit(60)
    W26Trick.spawn(W26Robo.Green, W26Monster.Zombie)
    W26Player.give(STONE_SWORD, 1)
    W26Player.take(STONE_SWORD, 1)
    W26Game.waitTick(1)
    W26Player.say("スタート！")
})
W26Event.onPlate(W26Plate.Stone, function () {
    W26Trick.markerSet(W26Robo.Red, PLANKS_OAK)
    W26Game.repeat(3, function () {
        W26Trick.markerSet(W26Robo.Lime, REDSTONE_BLOCK)
        W26Game.wait(1)
        W26Trick.markerBack(W26Robo.Lime)
        W26Game.wait(1)
    })
})
W26Event.onButton(W26Button.Crimson, function () {
    W26Player.effect(W26Effect.Jump, 5, 3)
    W26Player.warp(W26Robo.Random)
})
W26Event.every(3, function () {
    W26Trick.floorOff(W26Floor.Yellow)
    W26Game.wait(1.5)
    W26Trick.floorOn(W26Floor.Yellow)
    W26Trick.fx(W26Robo.Pink, W26Fx.Thunder)
})
W26Event.onOut(function () { W26Player.back() })
W26Event.onGot(DIAMOND, function () { W26Game.point(1, W26Change.Add) })
W26Event.onTouch(W26Lock.DoorRed, function () { W26Trick.keyOpen(TRIPWIRE_HOOK) })
W26Event.onTouch(W26Lock.Copper, function () { W26Trick.keyOpen(TRIPWIRE_HOOK) })
W26Event.onUse(BLAZE_ROD, function () { W26Trick.fx(W26Robo.Red, W26Fx.Firework) })
W26Event.onDown(W26MonsterDown.All, function () { W26Game.point(2, W26Change.Add) })
W26Event.onDown(W26MonsterDown.Zombie, function () { W26Game.point(1, W26Change.Add) })
W26Event.onHit(function () { W26Game.point(1, W26Change.Sub) })
W26Event.onDead(function () { W26Game.gameOver() })
W26Event.onPoint(3, function () { W26Game.clear() })
W26Event.onGoal(function () { W26Game.clear() })
W26Event.onTimeUp(function () { W26Game.gameOver() })
